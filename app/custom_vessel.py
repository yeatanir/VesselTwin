"""Custom vessel (pseudo, honest): a session-only clone of a template vessel's ParamDefs with the user's defaults.
Physics is borrowed from the template; nothing is written to the repo and nothing is registered globally.
ponytail: runs tier0/tier1 directly instead of core.api.solve, because api.solve looks vessels up in the global REGISTRY (shared by all sessions)."""
import dataclasses, re
from core import params as P
from core.registry import Vessel, load_all

# template key -> (registry vessel, card title, one-liner, editable fields (<= 8))
TEMPLATES = {
    "tube": ("cvd_tube", "Tube furnace / CVD", "Hot tube, boats, carrier gas",
             ["tube_id_in", "L_tube_cm", "T_furnace_C", "flow_sccm", "pressure_Pa", "duration_min", "x_substrate_cm", "L_hot_cm"]),
    "ampoule": ("ampoule", "Sealed ampoule", "Closed tube, vapour transport",
                ["L_cm", "D_mm", "T_source_C", "T_sink_C", "agent_mg_per_cm3", "inert_Ar_mbar", "tilt_deg"]),
    "stirred": ("flask", "Stirred vessel", "Flask, stir bar, reaction",
                ["volume_mL", "fill_frac", "bar_mm", "stir_rpm", "T_C", "k2_M_s", "C0_M"]),
    "bed": ("sorbent", "Packed bed", "Gas through sorbent pellets",
            ["bed_length_cm", "bed_id_cm", "particle_dp_mm", "T_K", "P_kPa", "flow_sccm", "y_feed"]),
    "photo": ("photoreactor", "Photoreactor", "Lamp, window, liquid",
              ["P_rad_W", "lambda_nm", "dist_cm", "A_irr_cm2", "path_cm", "c0_M", "t_irr_s"]),
}


def fields(template):
    """ParamDefs the form edits, in display order."""
    by = {d.name: d for d in load_all()[TEMPLATES[template][0]].defs}
    return [by[n] for n in TEMPLATES[template][3]]


def slug(name):
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_") or "custom"


def make(template, name, values, notes=""):
    """Clone the template's ParamDefs with `values` as new defaults (validated against the template bounds)."""
    base = load_all()[TEMPLATES[template][0]]
    vals = P.validate(base.defs, values)
    defs = [dataclasses.replace(d, default=vals[d.name]) for d in base.defs]
    name = name.strip() or "My vessel"
    return {"id": "custom_" + slug(name), "name": name, "template": template, "base": base.name, "defs": defs,
            "edited": {k: vals[k] for k in values}, "notes": notes}


def to_vessel(e):
    """Registry-compatible Vessel (not registered): borrowed tier0/solve with the cloned defaults."""
    b = load_all()[e["base"]]
    return Vessel(e["id"], e["name"], e["defs"], b.tier0, b.solve, b.units, lambda p: e["name"], b.source + " (borrowed)", [])


def save(ss, e):
    ss.setdefault("vt_custom_vessels", {})[e["id"]] = e


def note(e):
    return f"Custom vessel: borrowed physics from the {TEMPLATES[e['template']][1]} model, not validated for this geometry."


def run(e, n_mc=30):
    v = to_vessel(e)
    vals = P.defaults(v.defs)
    regime, margin, numbers = v.tier0(vals)
    pp = v.tier1(vals, synthetic=True, n=n_mc, seed=0).model_dump()
    d = {k: x["p50"] for k, x in pp["derived"].items() if x["p50"] is not None}
    return {"vessel": e["id"], "values": vals, "regime": regime.value, "margin": margin, "numbers": numbers, "derived": d,
            "units": v.units, "label": "hypothesis", "note": note(e)}


def stub(e):
    """Python source for vessels/<id>.py: the edited ParamDefs plus tier0/solve that delegate to the template vessel."""
    L = [f'"""{e["name"]}: stub generated by the VesselTwin Studio. Physics is BORROWED from the "{e["base"]}" vessel and not validated',
         'for this geometry. Replace tier0/solve with your own model, see docs/ADDING_A_VESSEL.md and vessels/_template.py."""',
         "import importlib", "from core.params import ParamDef as P", "from core.registry import REGISTRY, Vessel, register", "", "DEFS = ["]
    by = {d.name: d for d in e["defs"]}
    for n in e["edited"]:
        d = by[n]
        L.append(f"    P({d.name!r}, {d.label!r}, {d.unit!r}, {d.default!r}, {d.lo!r}, {d.hi!r}, {d.sigma!r}, group={d.group!r}, source=\"synthetic\"),")
    L += ["]", f"EDITED = {e['edited']!r}", f"BASE = {e['base']!r}  # template vessel whose physics is borrowed", "",
          "importlib.import_module(f'vessels.{BASE}')  # registers the template", "_B = REGISTRY[BASE]", "",
          "def _full(p):", "    return {**{d.name: d.default for d in _B.defs}, **p}", "",
          "def tier0(p):", "    return _B.tier0(_full(p))", "", "def solve(p):", "    return _B.solve(_full(p))", "",
          f"register(Vessel({e['id']!r}, {e['name']!r}, DEFS, tier0, solve, _B.units, lambda p: {e['name']!r}, \"tier1:borrowed\", []))"]
    notes = [f"# note: {l}" for l in e["notes"].splitlines() if l.strip()]
    return "\n".join(L[:2] + [""] + notes + L[2:]) + "\n"
